#include <float.h>
#include <stdio.h>

int main(void) {
    // 3/4 = 1/2 + 1/4 = 0.11 — конечная дробь, хранится точно
    printf("%.20f\n", 0.75f);                       // 0.75000000000000000000
    // 1/10 = 0.0(0011) — периодическая дробь, её приходится округлять
    printf("%.20f\n", 0.1f);                        // 0.10000000149011611938

    // 1.01001 = 1 + 1/4 + 1/32
    printf("%g\n", 1 + 1.0 / 4 + 1.0 / 32);         // 1.28125
    // 1.1101 = 1 + 1/2 + 1/4 + 1/16
    printf("%g\n", 1 + 1.0 / 2 + 1.0 / 4 + 1.0 / 16);   // 1.8125

    // 0.1, 0.2 и 0.3 округлены каждое по-своему, ошибки не совпадают
    printf("%.17g\n", 0.1 + 0.2);                   // 0.30000000000000004
    printf("%.17g\n", 0.3);                         // 0.29999999999999999

    // относительная погрешность 2^-24 и 2^-53: около 7 и 16 цифр
    printf("%g\n", FLT_EPSILON / 2);                // 5.96046e-08
    printf("%g\n", DBL_EPSILON / 2);                // 1.11022e-16
    // без потерь переживают перевод в число и обратно 6 и 15 цифр
    printf("%d %d\n", FLT_DIG, DBL_DIG);            // 6 15
    return 0;
}
