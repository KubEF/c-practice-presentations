#include <stdint.h>
#include <stdio.h>

int main(void) {
    uint8_t a = 0xE5;                       // 11100101
    uint8_t b = 0x5B;                       // 01011011
    int8_t c = (int8_t)0x97;                // 10010111 = -105

    // << дописывает нули справа: умножение на 2^n
    printf("%d\n", 1 << 8);                 // 256
    // старшие биты вылетают за край: умножение по модулю 256
    printf("%#x\n", (uint8_t)(a << 2));     // 0x94 = 10010100
    // >> для unsigned дописывает нули слева: деление на 2^n вниз
    printf("%#x\n", b >> 3);                // 0xb  = 00001011, 91 / 8 = 11

    // отрицательное знаковое: implementation-defined,
    // gcc делает арифметический сдвиг и копирует знаковый бит
    printf("%d\n", c >> 1);                 // -53  = 11001011
    // после приведения к unsigned сдвиг логический: слева ноль
    printf("%d\n", (uint8_t)c >> 1);        // 75   = 01001011

    // сдвиг на 0 значение не меняет
    printf("%d\n", b << 0);                 // 91
    // сдвиг на отрицательное число или на >= ширины типа — UB (C17 6.5.7):
    // b << -1 и 1u << 32 компилятор вправе превратить во что угодно
    return 0;
}
