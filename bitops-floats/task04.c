#include <stdio.h>

// степень двойки:  x = 0100000, x - 1 = 0011111, x & (x - 1) = 0
// другое число:    x = 0100110, x - 1 = 0100101, x & (x - 1) = 0100100
// вычитание гасит только младшую единицу, старшие остаются
int is_power_of_2(long long x) {
    // == старше &, поэтому скобки обязательны;
    // x = 0 тоже даёт x & (x - 1) = 0, поэтому нужна проверка x > 0
    return x > 0 && (x & (x - 1)) == 0;
}

//            x = 0101000
//        x - 1 = 0100111   хвост нулей стал единицами, младшая единица погасла
//           ~x = 1010111   единицы там, где у x нули
// ~x & (x - 1) = 0000111
unsigned zero_tail(unsigned x) {
    return ~x & (x - 1);
}

int main(void) {
    printf("%d %d\n", is_power_of_2(64), is_power_of_2(38));   // 1 0
    printf("%d %d\n", is_power_of_2(0), is_power_of_2(-8));    // 0 0
    printf("%#x\n", zero_tail(0x28));                          // 0x7 = 0000111
    return 0;
}
